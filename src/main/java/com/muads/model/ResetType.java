package com.muads.model;

public class ResetType {

    private int resetId;
    private String resetName;

    public ResetType() {
    }

    public int getResetId() {
        return resetId;
    }

    public void setResetId(int resetId) {
        this.resetId = resetId;
    }

    public String getResetName() {
        return resetName;
    }

    public void setResetName(String resetName) {
        this.resetName = resetName;
    }
}
